import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const base='http://127.0.0.1:5173';
const credentials=JSON.parse(readFileSync(new URL('../../.runtime/integration-test-account.json',import.meta.url),'utf8'));
const login=await fetch(base+'/api/minos/account',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(credentials)});
assert.equal(login.status,200);
const cookie=login.headers.get('set-cookie').split(';')[0];
assert.match(login.headers.get('set-cookie'),/HttpOnly/i);
assert.match(login.headers.get('set-cookie'),/SameSite=strict/i);
const body=await login.json();
assert.equal(body.accessToken,undefined);
assert.equal(body.refreshToken,undefined);
const me=await fetch(base+'/api/minos/account',{headers:{cookie}});assert.equal(me.status,200);
const denied=await fetch(base+'/api/business/users/me');assert.equal(denied.status,401);
const cross=await fetch(base+'/api/minos/account',{method:'POST',headers:{origin:'https://evil.invalid','sec-fetch-site':'cross-site','content-type':'application/json'},body:'{}'});assert.equal(cross.status,403);
const launch=await fetch(base+'/api/minos/connect',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({acknowledgeLocalAgent:true})});assert.equal(launch.status,200);
const connected=await launch.json();assert.equal(connected.ok,true);assert.equal(typeof connected.cwd,'string');
const models=await fetch(base+'/api/models',{headers:{cookie}});assert.equal(models.status,200);
const spoof=await fetch(base+'/api/models',{headers:{cookie,authorization:'Bearer fake','x-minos-internal':'fake'}});assert.equal(spoof.status,200);
const logout=await fetch(base+'/api/minos/account',{method:'DELETE',headers:{cookie}});assert.equal(logout.status,200);
const old=await fetch(base+'/api/models',{headers:{cookie}});assert.equal(old.status,401);
console.log('Unified cookie login, server-only credentials, CSRF, workspace cwd, SDK proxy and logout checks passed');
