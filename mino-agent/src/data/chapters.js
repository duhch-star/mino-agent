export const chapterIndex = Object.fromEntries(chapters.map(c => [c.title, c.id]))

export function chapterById(id) {
  return chapters.find(c => c.id === id)
}

// 按 prereq 依赖做拓扑排序，给出推荐学习路径（有环时退化为原顺序）
export function learningPath() {
  const order = []
  const remaining = [...chapters]
  while (remaining.length > 0) {
    const idx = remaining.findIndex(c =>
      (c.prereq || []).every(p => !chapterIndex[p] || order.some(o => o.title === p)),
    )
    if (idx === -1) { order.push(...remaining); break }
    order.push(remaining[idx])
    remaining.splice(idx, 1)
  }
  return order
}

